SELECT
    HASH(ITEM_ID) AS LISTING_KEY,
    ITEM_ID,
    LEGACY_ITEM_ID,
    TITLE,
    IS_ADULT_ONLY,
    PRIORITY_LISTING,
    PRICE_DISPLAY_CONDITION,
    ITEM_ORIGIN_DATE,
    ITEM_CREATION_DATE,
    ITEM_END_DATE
FROM {{ ref('ebay_data_json_expanded') }}
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY ITEM_ID
    ORDER BY LOAD_TIMESTAMP DESC, SILVER_CLEANSED_AT DESC
) = 1